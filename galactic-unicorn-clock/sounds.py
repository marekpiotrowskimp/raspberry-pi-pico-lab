# SadSounds — short mournful melody for game over (~6 seconds, C minor)
# ---------------------------------------------------------------------------
class SadSounds:
    beat = 0
    timer = Timer(-1)
    isPlaying = False

    # Slow descending C-minor melody: C5→B4→Bb4→Ab4→G4→F4→Eb4→C4
    # 5 Hz tick, each note held for 4 ticks (0.8s), silence between
    _MELODY = (
        523, 0, 0, 0,   # C5
        494, 0, 0, 0,   # B4
        466, 0, 0, 0,   # Bb4
        415, 0, 0, 0,   # Ab4
        392, 0, 0, 0,   # G4
        349, 0, 0, 0,   # F4
        311, 0, 0, 0,   # Eb4
        262, 0, 0, 0,   # C4
        -1, 0, 0, 0,    # release
    )
    _LEN = len(_MELODY)

    def __init__(self, galactic):
        self.galactic = galactic
        self.ch = galactic.synth_channel(0)  # reuse channel 0

    def _tick(self, timer):
        note = self._MELODY[self.beat]
        if note > 0:
            self.ch.frequency(note)
            self.ch.trigger_attack()
        elif note == -1:
            self.ch.trigger_release()
        self.beat = (self.beat + 1) % self._LEN
        if self.beat == 0:
            self.stop_play()

    def stop_play(self):
        if not self.isPlaying:
            return
        self.isPlaying = False
        self.timer.deinit()
        self.ch.play_tone(400, 0.0)
        self.galactic.play_synth()

    def play(self):
        if self.isPlaying:
            return
        self.isPlaying = True
        self.beat = 0
        self.ch.configure(
            waveforms=Channel.TRIANGLE,
            attack=0.05,
            decay=0.3,
            sustain=0.6,
            release=0.4,
            volume=14000 / 65535,
        )
        self.ch.frequency(self._MELODY[0])
        self.ch.trigger_attack()
        self.galactic.play_synth()
        self.timer.init(freq=5, mode=Timer.PERIODIC, callback=self._tick)



